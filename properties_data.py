def format_ar(ar):
    if ar >= 1_000_000:
        m = ar / 1_000_000
        if m == int(m):
            return f"{int(m)} M Ft"
        return f"{m:.1f} M Ft"
    return f"{ar:,} Ft".replace(",", " ")


